-- workflow-engine（pg feature）引擎自有 schema：幂等 DDL，每次启动执行。
-- 引擎表不持有指向消费方业务表的 FK；业务完整性（FK 到业务表等）由消费方在自己的迁移里以 ALTER TABLE 补充。
-- 消费方迁移顺序：先本文件（engine schema），再业务 schema。

-- 通用任务表：run_id 标识一次运行，scope_id 隔离运行内的分支（JOIN 按同 run 和 scope 判定），
-- 提交入口时以新任务 ID 创建运行。
CREATE TABLE IF NOT EXISTS tasks (
    workflow_id TEXT   NOT NULL,
    run_id      BIGINT NOT NULL DEFAULT 0,
    scope_id    BIGINT,
    task_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (task_id > 0),
    parent_task_ids BIGINT[] NOT NULL DEFAULT '{}',
    name        TEXT   NOT NULL,
    status      TEXT   NOT NULL CHECK (
        status IN ('pending', 'collecting', 'running', 'succeeded', 'failed', 'superseded')
    ),
    lease_until TIMESTAMPTZ,
    available_at TIMESTAMPTZ,
    attempt     INT    NOT NULL DEFAULT 0,
    input_json  JSONB  NOT NULL CHECK (status <> 'collecting' OR jsonb_typeof(input_json) = 'object'),
    output_json JSONB,
    error       TEXT,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 写入数据库元数据，供数据库客户端查看；每次执行 schema 时同步更新说明。
COMMENT ON TABLE tasks IS '工作流任务实例及其执行状态；以 task_id 唯一定位一条任务，同一次 run 可包含多个任务。';
COMMENT ON COLUMN tasks.workflow_id IS '工作流标识；用于隔离任务和限定调度范围。';
COMMENT ON COLUMN tasks.run_id IS '运行分组键；与 scope_id 一起限定 JOIN 汇合、前驱等待及失败级联，后继继承源任务的值；提交入口时以新任务 ID 创建运行。';
COMMENT ON COLUMN tasks.scope_id IS '运行内的执行分组；实例及父子关系保存在 scopes 表；进入子图创建实例，退出恢复父实例，NULL 为运行根作用域。';
COMMENT ON COLUMN tasks.parent_task_ids IS '来源任务 ID 数组，引用同一 workflow_id 下的 task_id；入口为空，成功和失败后继均记录源任务，JOIN 累积并去重所有贡献者。';
COMMENT ON COLUMN tasks.task_id IS '数据库生成的任务主键；在任务表中唯一，允许跳号，用于任务定位、依赖引用和状态结算；同一任务重新认领时保持不变。';
COMMENT ON COLUMN tasks.name IS '工作流图中注册的节点名；调度器据此选择执行节点，同一节点可产生多条任务记录。';
COMMENT ON COLUMN tasks.status IS '任务状态：pending 待认领，collecting 收集 JOIN 输入，running 已认领，succeeded 成功，failed 永久失败，superseded 失败已由后继接管。';
COMMENT ON COLUMN tasks.lease_until IS '本次认领的租约截止时间，执行及结算期间持续续租；NULL 表示无有效租约，无有效租约的 running 任务可重新认领；结算或释放时清空。';
COMMENT ON COLUMN tasks.available_at IS '下次允许被认领的时间；NULL 表示立即可认领，退避重试时写入未来时间。';
COMMENT ON COLUMN tasks.attempt IS '认领代次；初始为 0，每次认领加 1，用于写入校验；超出引擎重试预算的认领只处理最终失败，不再执行业务。';
COMMENT ON COLUMN tasks.input_json IS '节点输入的 JSON 值；结构由节点输入类型决定，成功汇合任务按对象键合并贡献。';
COMMENT ON COLUMN tasks.output_json IS '节点成功输出的 JSON 值；结构由节点输出类型决定，尚未写入输出时为 SQL NULL。';
COMMENT ON COLUMN tasks.error IS '失败、被后继接管或退避重试的原因文本，也记录重试预算耗尽及依赖失败原因；成功结算或新业务认领时清空。';
COMMENT ON COLUMN tasks.created_at IS '任务记录创建时间，由数据库时钟写入。';
COMMENT ON COLUMN tasks.updated_at IS '任务记录最近更新时间；由仓储在认领、结算、来源合并或租约变更时显式更新，无自动更新触发器。';

-- 按绑定工作流、状态、可认领时间和租约查找可认领的任务。
CREATE INDEX IF NOT EXISTS idx_tasks_claim
ON tasks(workflow_id, status, available_at, lease_until);

-- JOIN 分组合并、前驱就绪与失败检查。
CREATE INDEX IF NOT EXISTS idx_tasks_scope_name
ON tasks(workflow_id, run_id, scope_id, name, status);

-- 子图的执行实例，仅保存身份和父子关系，无独立任务状态或调度生命周期。
CREATE TABLE IF NOT EXISTS scopes (
    workflow_id TEXT NOT NULL,
    scope_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (scope_id > 0),
    run_id BIGINT NOT NULL,
    subgraph_id TEXT NOT NULL,
    parent_scope_id BIGINT,
    trigger_task_id BIGINT NOT NULL,
    UNIQUE (workflow_id, scope_id),
    FOREIGN KEY (workflow_id, parent_scope_id) REFERENCES scopes(workflow_id, scope_id)
);
CREATE INDEX IF NOT EXISTS idx_scopes_parent ON scopes(workflow_id, run_id, parent_scope_id);
